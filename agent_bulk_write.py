def targets(jobs, regen=False):
    now = datetime.datetime.utcnow() + datetime.timedelta(hours=9)
    days = {str(now.date()), str(now.date() - datetime.timedelta(days=1))}
    out = []
    for j in jobs:
        if (j.get("posted") or "")[:10] not in days:
            continue
        if j.get("aw") == 1 and not regen:
            continue
        f = os.path.join(AS.ART_DIR, j["id"] + ".html")
        if not regen and os.path.exists(f) and "<!-- agent-written -->" in open(f, encoding="utf-8").read():
            continue
        if j.get("type") in EXCLUDE_TYPE or EXCLUDE_TITLE.search(j["title"]):
            continue
        out.append(j)
    return sorted(out, key=lambda x: (x["posted"], x["id"]), reverse=True)


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    dry = "--dry" in sys.argv
    regen = "--regen" in sys.argv
    jobs = json.load(open(AS.JOBS_JSON, encoding="utf-8"))
    tg = targets(jobs, regen)
    print(f"대상 {len(tg)}건")
    role_of = {j["id"]: find_role(j["title"])["label"] for j in tg}
    dls = {}
    for j in tg:
        dls.setdefault(role_of[j["id"]], []).append(j["deadline"])
    ok, fail, short = [], [], []
    for j in tg:
        peers = dls.get(role_of[j["id"]]) if len(dls.get(role_of[j["id"]], [])) > 1 else None
        sec = build_sections(j, peers)
        html = AS.build_agent(j, sec, jobs)
        text = re.sub(r"<[^>]+>", "", html)
        ko = len(re.findall(r"[가-힣]", text))
        banned = [w for w in AS.BANNED if re.search(w, html)]
        if banned:
            fail.append((j["id"], str(banned)))
            continue
        if ko < 2000:
            short.append((j["id"], ko))
            continue
        if not dry:
            with open(os.path.join(AS.ART_DIR, j["id"] + ".html"), "w", encoding="utf-8") as fh:
                fh.write(html)
        ok.append((j["id"], ko))
    print(f"작성 {len(ok)} / 분량미달 {len(short)} / 금지표현 {len(fail)}")
    for x in short:
        print("  SHORT", x)
    for x in fail:
        print("  BANNED", x)
    ks = [k for _, k in ok]
    if ks:
        print(f"한글 평균 {sum(ks)//len(ks)}자 최소 {min(ks)}자 최대 {max(ks)}자")
    if not dry and ok:
        print("OK_IDS=" + ",".join(i for i, _ in ok))


if __name__ == "__main__":
    main()

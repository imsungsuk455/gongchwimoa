def parse_people(title, summary):
    for s in summary or []:
        m = re.search(r"(\d+)\s*명", s)
        if m and int(m.group(1)) > 0:
            return m.group(1)
    m = re.search(r"(\d+)\s*명", title)
    return m.group(1) if m and int(m.group(1)) > 0 else None


def parse_role_label(title):
    m = re.search(r"\(([^)]{2,25})\)", title)
    if m:
        inner = re.sub(r"\d+\s*명", "", m.group(1)).strip(" ,·")
        if inner and not re.search(r"^\d|년|회$", inner):
            return inner
    return None



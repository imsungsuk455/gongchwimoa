def josa(word, with_b, without_b):
    """받침 유무에 따라 조사를 고른다."""
    w = word.strip()
    if not w:
        return without_b
    ch = w[-1]
    if "가" <= ch <= "힣":
        return with_b if (ord(ch) - 0xAC00) % 28 else without_b
    if ch.isdigit() or ch.isalpha():
        return without_b
    return with_b


